"""The function library as SymPy functions: the fit models, in the same form as a project's __sympy__ functions.

Each entry is what a __sympy__ row holds - a name, its kind ("expression", or "code" for what SymPy cannot
write), its parameters with their starting values, the formula - plus where it is shown (category,
description, keywords, goals), how many independent variables it has (ndim) and the estimator of its
starting values (guess, step 2 of dev/plans/sympy_library_plan.txt). The entries are generated from the
classes in app/functions by dev/tools/translate_function_library.py; dev/tests/test_function_library.py
checks that each gives the class's numbers.

The guards keep the formulas readable and the numbers the classes' own - functions of their own name,
computed by the classes' numpy helpers and differentiated as each says:
- pos(s): |s|, and EPS where it would be 0 - a width, a rate, a shape that must stay positive;
- nz(d): d, and EPS where it would be 0 - a denominator;
- safe(x): x, kept EPS away from 0 on its own side;
- finite(v): v, and 0 where it is not finite - a density's infinity at its edge.
"""
from __future__ import annotations

from collections.abc import Callable, Mapping
from typing import Any

import numpy as np
import sympy as sp

#: How close to zero a guard lets a value come.
EPS = 1e-12

class _Guard(sp.Function):
    """A guard: computed as the classes' numpy helper did (NUMPY_MODULES), differentiated as fdiff says."""


class pos(_Guard):  # noqa: N801 - the expressions' own names
    """pos(s): |s|, and EPS where it would be 0 - a width, a rate, a shape that must stay positive."""

    def fdiff(self, argindex: int = 1) -> sp.Expr:
        del argindex
        return sp.sign(self.args[0])


class nz(_Guard):  # noqa: N801
    """nz(d): d, and EPS where it would be 0 - a denominator."""

    def fdiff(self, argindex: int = 1) -> sp.Expr:
        del argindex
        return sp.Integer(1)


class safe(_Guard):  # noqa: N801
    """safe(x): x, kept EPS away from 0 on its own side."""

    def fdiff(self, argindex: int = 1) -> sp.Expr:
        del argindex
        return sp.Integer(1)


class finite(_Guard):  # noqa: N801
    """finite(v): v, and 0 where it is not finite (numpy's nan_to_num) - a density's infinity at its edge."""

    def fdiff(self, argindex: int = 1) -> sp.Expr:
        del argindex
        return sp.Integer(1)


#: The guards by the names the expressions use.
GUARDS: dict[str, type[_Guard]] = {"pos": pos, "nz": nz, "safe": safe, "finite": finite}


def _pos(value: Any) -> np.ndarray:
    arr = np.asarray(value, dtype=float)
    return np.where(np.abs(arr) < EPS, EPS, np.abs(arr))


def _nz(value: Any) -> np.ndarray:
    arr = np.asarray(value, dtype=float)
    return np.where(np.abs(arr) < EPS, EPS, arr)


def _safe(value: Any) -> np.ndarray:
    arr = np.asarray(value, dtype=float)
    return np.where(np.abs(arr) < EPS, np.sign(arr + EPS) * EPS, arr)


def _finite(value: Any) -> np.ndarray:
    return np.nan_to_num(np.asarray(value, dtype=float), nan=0.0, posinf=0.0, neginf=0.0)


def _maximum(*values: Any) -> Any:
    result = values[0]
    for value in values[1:]:
        result = np.maximum(result, value)
    return result


def _minimum(*values: Any) -> Any:
    result = values[0]
    for value in values[1:]:
        result = np.minimum(result, value)
    return result


#: What lambdify reads the expressions with: the guards as the classes computed them, Max/Min element-wise.
NUMPY_MODULES: list[Any] = [{"pos": _pos, "nz": _nz, "safe": _safe, "finite": _finite, "Max": _maximum,
                             "Min": _minimum}, "scipy", "numpy"]


def identifier(name: str) -> str:
    """The name an expression calls a library function by: "Gaussian peak" -> Gaussian_peak."""
    import re

    return re.sub(r"\W+", "_", str(name)).strip("_")


def called_names(code: str) -> list[str]:
    """The names *code* calls as functions - Gaussian_peak(x, A, mu, s) - in order, once each."""
    import re

    return list(dict.fromkeys(re.findall(r"\b([A-Za-z_]\w*)\s*\(", str(code))))


class CallError(ValueError):
    """A function that calls itself (through others), or one that cannot be called here."""


def _callable(name: str, params: list[str], ndim: int, code: str, kind: str, functions: Mapping[str, Mapping],
              chain: tuple[str, ...]) -> Any:
    """*name* as an expression calls it: a Lambda of its formula (exact through derivatives), or for code a
    numeric function (implemented_function: no exact derivative)."""
    variables = [sp.Symbol("x")] if ndim == 1 else [sp.Symbol("x"), sp.Symbol("y")]
    symbols = [sp.Symbol(param) for param in params]
    if kind == "expression":
        body = sp.sympify(str(code).replace("^", "**"),
                          locals=sympy_locals(params, ndim, code=code, functions=functions, chain=chain))
        return sp.Lambda((*variables, *symbols), body)
    numeric_function = numeric({"name": name, "kind": "code", "code": code, "params": params, "ndim": ndim})
    implementation = (lambda x, *p: numeric_function(x, np.asarray(p, dtype=float))) if ndim == 1 else \
        (lambda x, y, *p: numeric_function(x, y, np.asarray(p, dtype=float)))
    from sympy.utilities.lambdify import implemented_function

    return implemented_function(sp.Function(name), implementation)


def sympy_locals(parameters: list[str], ndim: int = 1, *, code: str = "",
                 functions: Mapping[str, Mapping] | None = None, chain: tuple[str, ...] = ()) -> dict[str, Any]:
    """The names an expression is read with: x (and y), its parameters, the guards - and the functions *code*
    calls: a project's own (*functions*, the __sympy__ rows by name: trusted, expression or code) or the
    library's. *chain* is who is calling, to refuse a function that calls itself."""
    names: dict[str, Any] = {"x": sp.Symbol("x"), "y": sp.Symbol("y"), "z": sp.Symbol("z")}
    for name in called_names(code):
        if name in GUARDS or name in parameters or hasattr(sp, name):
            continue  # pos, a parameter, exp, sin...: not a function of the project or the library
        if name in chain:
            raise CallError(f"{' -> '.join((*chain, name))}: a function cannot call itself.")
        row = (functions or {}).get(name)
        if row is not None:
            from app.data_operations import sympy_store

            if not sympy_store.is_trusted(row):
                raise CallError(f"'{name}' is not trusted on this computer: it cannot be called.")
            info = sympy_store.payload(row)
            names[name] = _callable(name, list(info["params"]), int(info["ndim"]), str(info["code_string"]),
                                    str(info["source_type"]), functions or {}, (*chain, name))
            continue
        entry = get(name) or next((item for item in ENTRIES if identifier(item["name"]) == name), None)
        if entry is not None:
            names[name] = _callable(name, list(entry["params"]), int(entry["ndim"]), str(entry["code"]),
                                    str(entry["kind"]), functions or {}, (*chain, name))
    names.update(GUARDS)
    names.update({name: sp.Symbol(name) for name in parameters})
    del ndim
    return names


def expression(entry: Mapping[str, Any]) -> sp.Expr:
    """An "expression" entry's formula as SymPy, its guards as the functions pos, nz, safe and finite."""
    if entry.get("kind") != "expression":
        raise ValueError(f"'{entry.get('name')}' is a code function: it has no SymPy expression.")
    return sp.sympify(str(entry["code"]), locals=sympy_locals(list(entry["params"]), int(entry.get("ndim", 1)),
                                                              code=str(entry["code"]), chain=(str(entry["name"]),)))


def numeric(entry: Mapping[str, Any]) -> Callable[..., np.ndarray]:
    """The entry as numpy: f(x, p) - or f(x, y, p) for a surface - p the parameters in order."""
    params = [sp.Symbol(name) for name in entry["params"]]
    ndim = int(entry.get("ndim", 1))
    variables = (sp.Symbol("x"),) if ndim == 1 else (sp.Symbol("x"), sp.Symbol("y"))
    if entry.get("kind") == "expression":
        function = sp.lambdify((*variables, *params), expression(entry), modules=NUMPY_MODULES)

        def evaluate(*args: Any) -> np.ndarray:
            *coordinates, p = args
            arrays = [np.asarray(value, dtype=float) for value in coordinates]
            value = function(*arrays, *np.asarray(p, dtype=float))
            return np.broadcast_to(np.asarray(value, dtype=float), np.broadcast(*arrays).shape).copy()
        return evaluate
    return _code_function(entry)


def _code_function(entry: Mapping[str, Any]) -> Callable[..., np.ndarray]:
    """A "code" entry (shipped with the application, so trusted): its body as the class's execute ran it."""
    import scipy.special as spsp

    from app.plugin_api.functions import base

    ndim = int(entry.get("ndim", 1))
    head = "def execute(x, p):\n" if ndim == 1 else "def execute(x, y, p):\n"
    body = "".join(f"    {line}\n" for line in str(entry["code"]).splitlines())
    namespace: dict[str, Any] = {"np": np, "spsp": spsp, **{name: getattr(base, name) for name in
                                                            ("_pos", "_eps", "_safe_x", "_positive_x")}}
    exec(compile(head + body, f"<library {entry['name']}>", "exec"), namespace)  # noqa: S102 - the app's own source
    return namespace["execute"]


def entries(*, ndim: int | None = None) -> tuple[dict, ...]:
    """The library's functions; only the curves (1) or the surfaces (2) with *ndim*."""
    return tuple(entry for entry in ENTRIES if ndim is None or int(entry["ndim"]) == ndim)


def get(name: str) -> dict | None:
    """The function called *name* (its name, or the class it was translated from)."""
    return next((entry for entry in ENTRIES if name in (entry["name"], entry.get("class_name"))), None)


